// ========== 导出器 ==========
// 清理编辑属性 + 下载/复制 HTML
class Exporter {
  constructor(eventBus, iframeManager, annotator) {
    this.bus = eventBus;
    this.iframe = iframeManager;
    this.annotator = annotator;
  }

  // 清理所有编辑属性
  cleanHTML(doc) {
    if (!doc) return '';
    const clone = doc.documentElement.cloneNode(true);

    // 移除编辑器注入的元素
    clone.querySelectorAll('[data-editor-injected]').forEach(el => el.remove());

    // 移除编辑属性
    const editAttrs = ['data-eid', 'data-type', 'data-editable', 'data-role', 'data-user-override', 'contenteditable'];
    clone.querySelectorAll('*').forEach(el => {
      editAttrs.forEach(attr => el.removeAttribute(attr));
    });

    // 添加版本元数据注释
    const meta = `<!--\n  Generated by HTML Visual Editor\n  Date: ${new Date().toISOString()}\n  Version: 1.0.0\n-->`;

    return '<!DOCTYPE html>\n' + meta + '\n' + clone.outerHTML;
  }

  // 下载 HTML 文件
  download() {
    const doc = this.iframe.getDocument();
    if (!doc) return;

    const html = this.cleanHTML(doc);
    const blob = new Blob([html], { type: 'text/html;charset=utf-8' });
    const url = URL.createObjectURL(blob);

    const date = new Date().toISOString().slice(0, 10);
    const rand = Math.random().toString(36).substring(2, 6);
    const filename = `page-${date}-${rand}.html`;

    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);

    this.bus.emit('exported', { type: 'download', filename });
  }

  // 复制 HTML 代码到剪贴板
  async copyToClipboard() {
    const doc = this.iframe.getDocument();
    if (!doc) return;

    const html = this.cleanHTML(doc);
    try {
      await navigator.clipboard.writeText(html);
      this.bus.emit('exported', { type: 'copy', success: true });
    } catch (e) {
      // 降级方案
      const textarea = document.createElement('textarea');
      textarea.value = html;
      textarea.style.position = 'fixed';
      textarea.style.opacity = '0';
      document.body.appendChild(textarea);
      textarea.select();
      try {
        document.execCommand('copy');
        this.bus.emit('exported', { type: 'copy', success: true });
      } catch (e2) {
        this.bus.emit('exported', { type: 'copy', success: false });
      }
      document.body.removeChild(textarea);
    }
  }

  // 生成分享链接（基于 IndexedDB）
  async shareLink() {
    const doc = this.iframe.getDocument();
    if (!doc) return;

    const html = this.cleanHTML(doc);
    const contentId = 'page-' + Date.now() + '-' + Math.random().toString(36).substring(2, 8);

    try {
      // 存入 IndexedDB
      const db = await this._openDB();
      await this._putData(db, 'pages', { id: contentId, html: html, timestamp: Date.now() });

      // 生成分享链接
      const baseUrl = window.location.origin + window.location.pathname;
      const shareUrl = `${baseUrl}#view=${contentId}`;

      this.bus.emit('share-link-generated', { url: shareUrl, id: contentId });
      return shareUrl;
    } catch (e) {
      console.error('[Exporter] share error:', e);
      this.bus.emit('share-link-generated', { url: null, error: e.message });
    }
  }

  // 导出 AI 交接文件
  exportAIHandoff() {
    const doc = this.iframe.getDocument();
    if (!doc) return;

    const elements = [];
    const allElements = doc.querySelectorAll('[data-eid]');

    allElements.forEach(el => {
      const eid = el.getAttribute('data-eid');
      const type = el.getAttribute('data-type') || 'unknown';
      const tag = el.tagName.toLowerCase();
      const text = (el.textContent || '').trim().slice(0, 100);
      const cls = el.className || '';

      elements.push({ eid, type, tag, class: cls, text });
    });

    const handoff = `# AI 交接文件

## 页面结构概览

共 ${elements.length} 个可编辑元素。

## 可编辑元素列表

${elements.map(e => `### ${e.eid}
- 标签: \`${e.tag}\`
- 类型: ${e.type}
- class: \`${e.class}\`
- 内容摘要: "${e.text}"
`).join('\n')}

## 约束要求

1. 保持现有布局结构，不要删除已有的 section/div 容器
2. 修改文字时保持标签不变
3. 修改图片时保持 alt 属性
4. 修改样式时使用内联 style 或追加到 <style> 标签

## 当前 HTML

\`\`\`html
${this.cleanHTML(doc)}
\`\`\`
`;

    const blob = new Blob([handoff], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'ai-handoff.md';
    a.click();
    URL.revokeObjectURL(url);

    this.bus.emit('exported', { type: 'ai-handoff' });
  }

  // IndexedDB 辅助方法
  _openDB() {
    return new Promise((resolve, reject) => {
      const request = indexedDB.open('HtmlVisualEditor', 1);
      request.onerror = () => reject(request.error);
      request.onsuccess = () => resolve(request.result);
      request.onupgradeneeded = (e) => {
        const db = e.target.result;
        if (!db.objectStoreNames.contains('pages')) {
          db.createObjectStore('pages', { keyPath: 'id' });
        }
      };
    });
  }

  _putData(db, store, data) {
    return new Promise((resolve, reject) => {
      const tx = db.transaction(store, 'readwrite');
      const request = tx.objectStore(store).put(data);
      request.onsuccess = () => resolve(request.result);
      request.onerror = () => reject(request.error);
    });
  }

  async loadSharedPage(contentId) {
    try {
      const db = await this._openDB();
      const result = await this._getData(db, 'pages', contentId);
      return result ? result.html : null;
    } catch (e) {
      console.error('[Exporter] load shared page error:', e);
      return null;
    }
  }

  _getData(db, store, key) {
    return new Promise((resolve, reject) => {
      const tx = db.transaction(store, 'readonly');
      const request = tx.objectStore(store).get(key);
      request.onsuccess = () => resolve(request.result);
      request.onerror = () => reject(request.error);
    });
  }
}

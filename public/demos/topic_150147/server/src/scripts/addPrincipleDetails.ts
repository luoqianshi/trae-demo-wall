async function updateAllTasks(): Promise<void> {
  const tasks = db.prepare('SELECT id, title, category, reference_materials FROM tasks ORDER BY id').all() as any[];

  console.log(`总任务数: ${tasks.length}`);
  console.log(`有详细讲解定义的任务数: ${Object.keys(details).length}`);

  let updated = 0;
  let skipped = 0;
  let missing = 0;

  const updateStmt = db.prepare('UPDATE tasks SET reference_materials = ? WHERE id = ?');

  for (const task of tasks) {
    const detail = details[task.id];

    if (!detail) {
      missing++;
      console.log(`  ⚠ [${task.id}] ${task.title} — 缺少详细讲解定义`);
      continue;
    }

    // 检查是否已有详细讲解
    if (task.reference_materials && task.reference_materials.includes('【详细讲解】')) {
      skipped++;
      console.log(`  ⊘ [${task.id}] ${task.title} — 已有详细讲解，跳过`);
      continue;
    }

    // 追加详细讲解到reference_materials末尾
    const newRefs = (task.reference_materials || '') + '\n' + detail;
    updateStmt.run(newRefs, task.id);
    updated++;
    console.log(`  ✓ [${task.id}] ${task.title} — 已更新`);
  }

  console.log(`\n===== 更新完成 =====`);
  console.log(`已更新: ${updated}`);
  console.log(`已跳过: ${skipped}`);
  console.log(`缺少定义: ${missing}`);
  console.log(`总计: ${tasks.length}`);
}


// 获取所有特殊植物ID
export function getSpecialPlantIds() {
  return Object.keys(specialPlantData);
}

// 获取随机特殊植物
export function getRandomSpecialPlant(excludeIds = []) {
  const available = Object.keys(specialPlantData).filter(id => !excludeIds.includes(id));
  if (available.length === 0) return null;
  const id = available[Math.floor(Math.random() * available.length)];
  return { id, ...specialPlantData[id] };
}

// 检查是否为特殊植物
export function isSpecialPlant(plantId) {
  return specialPlantData.hasOwnProperty(plantId);
}

export default specialPlantData;

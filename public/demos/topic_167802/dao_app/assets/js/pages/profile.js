/* 我的 · 修行者 */
(function (App) {
  'use strict';
  var h = App.h, UI = App.UI, Store = App.Store;

  function render() {
    var st = Store.get();
    var rp = Store.realmProgress();
    var wrap = h('div');

    // 档案卡
    wrap.appendChild(h('.cultivator', {}, [
      h('.row.between', {}, [
        h('div', {}, [
          h('.name', { text: st.name }),
          h('.realm', { text: rp.cur.name + ' · ' + rp.cur.sub })
        ]),
        h('button.btn.ghost', { text: '改名号', onclick: function () { editName(); } })
      ]),
      UI.progress(rp.pct),
      h('.small.muted', { style: { marginTop: '0.4rem' }, text: '修为 ' + st.cultivation + (rp.next ? ' · 距 ' + rp.next.name + rp.next.sub + ' 还需 ' + rp.remain : ' · 已臻圆满') })
    ]));

    // 数据统计
    wrap.appendChild(h('.grid3', {}, [
      stat('连续修行', st.streak + ' 天'),
      stat('已解锁功法', st.unlockedGongfa.length),
      stat('问卜次数', st.divinationLog.length)
    ]));

    // 历史记录
    wrap.appendChild(h('.section-title', { text: '修行记录' }));
    wrap.appendChild(recordItem('☯', '问卜日志', st.divinationLog.length + ' 条', function () { showDivLog(st); }));
    wrap.appendChild(recordItem('命', '命盘记录', st.baziRecords.length + ' 条', function () { showBaziLog(st); }));
    wrap.appendChild(recordItem('相', '状态记录', st.faceRecords.length + ' 条', function () { showFaceLog(st); }));

    // 设置
    wrap.appendChild(h('.section-title', { text: '设置' }));
    wrap.appendChild(h('.card', {}, [
      h('.row.between', {}, [
        h('div', {}, [ h('.card-title', { text: '主题' }), h('.card-sub', { text: '深墨绿修仙风（Demo 固定）' }) ]),
        h('span.tag.gold', { text: '深色' })
      ])
    ]));
    wrap.appendChild(h('button.btn.block', { text: '重置 Demo 数据', style: { borderColor: 'var(--danger)', color: 'var(--danger)' }, onclick: function () { confirmReset(); } }));

    wrap.appendChild(h('.disclaimer', { html: '本 App 为 <b>Demo 演示</b>，数据保存在本地浏览器；命理、面相、占卜内容为文化体验与启发式参考。' }));
    wrap.appendChild(h('.small.muted.center', { style: { marginTop: '0.8rem' }, text: 'Generated by Trae Work · 凡人修仙 Demo' }));
    return wrap;
  }

  function stat(label, val) {
    return h('.card.center', { style: { margin: 0, padding: '0.8rem 0.4rem' } }, [
      h('div', { text: String(val), style: { fontSize: '1.25rem', fontWeight: '700', color: 'var(--accent)' } }),
      h('.small.muted', { text: label })
    ]);
  }

  function recordItem(ico, title, sub, onclick) {
    return h('.list-item', { onclick: onclick }, [
      h('.li-ico', { text: ico }),
      h('.li-main', {}, [ h('.li-title', { text: title }), h('.li-sub', { text: sub }) ]),
      h('.li-arrow', { text: '›' })
    ]);
  }

  function editName() {
    var input = h('input.input', { type: 'text', value: Store.get().name, maxlength: 12 });
    var content = h('div', {}, [
      h('.field', {}, [ h('label', { text: '修行者名号' }), input ]),
      h('button.btn.primary.block', { text: '保存', onclick: function () {
        var v = input.value.trim();
        if (v) { Store.set({ name: v }); UI.closeModal(); UI.toast('名号已更新'); App.Router.render(); }
      }})
    ]);
    UI.modal('修改名号', content);
  }

  function showDivLog(st) {
    if (!st.divinationLog.length) return emptyModal('问卜日志', '还没有问卜记录');
    var box = h('div');
    st.divinationLog.forEach(function (r) {
      box.appendChild(h('.card', {}, [
        h('.row.between', {}, [ h('.card-title', { text: r.name }), h('.tag.gold', { text: r.luck }) ]),
        r.question ? h('.card-sub', { text: '所问：' + r.question }) : null,
        h('.small.muted', { text: App.fmtTime(r.time) }),
        h('.quote', { style: { marginTop: '0.4rem' }, text: r.word })
      ]));
    });
    UI.modal('问卜日志', box);
  }

  function showBaziLog(st) {
    if (!st.baziRecords.length) return emptyModal('命盘记录', '还没有命盘记录');
    var box = h('div');
    st.baziRecords.forEach(function (r) {
      box.appendChild(h('.card', {}, [
        h('.card-title', { text: r.birth.date + ' ' + r.timeName }),
        h('.small.muted', { text: '四柱：' + r.pillars.map(function (p) { return p.gan + p.zhi; }).join(' ') }),
        h('.quote', { style: { marginTop: '0.4rem' }, text: r.reading.summary })
      ]));
    });
    UI.modal('命盘记录', box);
  }

  function showFaceLog(st) {
    if (!st.faceRecords.length) return emptyModal('状态记录', '还没有面相状态记录');
    var box = h('div');
    st.faceRecords.forEach(function (r) {
      box.appendChild(h('.card', {}, [
        h('.row.between', {}, [ h('.card-title', { text: '状态分 ' + r.score }), h('.tag.green', { text: r.qise }) ]),
        h('.small.muted', { text: App.fmtTime(r.time) }),
        h('.quote', { style: { marginTop: '0.4rem' }, text: r.advice })
      ]));
    });
    UI.modal('状态记录', box);
  }

  function emptyModal(title, msg) {
    UI.modal(title, h('.empty', {}, [ h('.em-ico', { text: '∅' }), h('div', { text: msg }) ]));
  }

  function confirmReset() {
    var content = h('div', {}, [
      h('p', { text: '确定要清空所有修行进度、记录与设置吗？此操作不可撤销。', style: { marginBottom: '1rem' } }),
      h('.row', { style: { gap: '0.6rem' } }, [
        h('button.btn.block', { text: '取消', onclick: function () { UI.closeModal(); } }),
        h('button.btn.primary.block', { text: '确认重置', style: { background: 'var(--danger)', borderColor: 'var(--danger)' }, onclick: function () {
          Store.reset(); UI.closeModal(); UI.toast('已重置'); App.Router.go('home');
        }})
      ])
    ]);
    UI.modal('重置 Demo 数据', content);
  }

  App.Pages = App.Pages || {};
  App.Pages.profile = { title: '设置 · 我的', tab: 'home', back: 'home', render: render };
})(window.App);

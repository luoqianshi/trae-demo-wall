  function chatWithAI(message, ctx) {
    return App.delay(700 + Math.random() * 600).then(function () {
      var text = (message || '').toLowerCase();
      var matched = null;
      for (var i = 0; i < RULES.length; i++) {
        for (var j = 0; j < RULES[i].kw.length; j++) {
          if (text.indexOf(RULES[i].kw[j].toLowerCase()) >= 0) { matched = RULES[i].reply; break; }
        }
        if (matched) break;
      }
      var reply = matched || App.pick(FALLBACK);
      // 带上下文（从模块跳转提问）
      if (ctx && ctx.hint && !matched) {
        reply = ctx.hint;
      }
      return reply;
    });
  }

  App.Mock = App.Mock || {};
  App.Mock.chatWithAI = chatWithAI;
  App.Mock.AI_SUGGEST = SUGGEST;

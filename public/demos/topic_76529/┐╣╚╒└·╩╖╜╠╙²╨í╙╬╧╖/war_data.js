// 关卡题目绑定管理
// ============================================

/** 关卡题目绑定数据 */
let levelQuestionBindings = {};

/** 初始化关卡题目绑定（从存档加载或默认） */
function initLevelBindings() {
    try {
        const saved = localStorage.getItem('levelBindings');
        if (saved) {
            levelQuestionBindings = JSON.parse(saved);
            if (typeof Game !== 'undefined' && Game.log) {
                Game.log('关卡题目绑定已加载');
            }
        }
    } catch (e) {
        if (typeof Game !== 'undefined' && Game.log) {
            Game.log('关卡题目绑定加载失败: ' + e.message, 'error');
        }
    }
}

/** 保存关卡题目绑定 */
function saveLevelBindings() {
    try {
        localStorage.setItem('levelBindings', JSON.stringify(levelQuestionBindings));
        if (typeof Game !== 'undefined' && Game.log) {
            Game.log('关卡题目绑定已保存');
        }
    } catch (e) {
        if (typeof Game !== 'undefined' && Game.log) {
            Game.log('关卡题目绑定保存失败: ' + e.message, 'error');
        }
    }
}

/**
 * 获取关卡绑定的题目
 * @param {string} cityId - 城市ID（关卡ID）
 * @returns {Array} 绑定的题目数组
 */
function getLevelQuestions(cityId) {
    const bindings = levelQuestionBindings[cityId];
    if (bindings && bindings.length > 0) {
        return bindings.map(id => getQuestionById(id)).filter(q => q);
    }
    return shuffle(allSubjectQuestions).slice(0, 10);
}

/**
 * 设置关卡绑定题目
 * @param {string} cityId - 城市ID（关卡ID）
 * @param {Array} questionIds - 题目ID数组
 */
function setLevelQuestions(cityId, questionIds) {
    levelQuestionBindings[cityId] = questionIds;
    saveLevelBindings();
    if (typeof Game !== 'undefined' && Game.log) {
        Game.log(`关卡 ${cityId} 绑定了 ${questionIds.length} 道题目`);
    }
}


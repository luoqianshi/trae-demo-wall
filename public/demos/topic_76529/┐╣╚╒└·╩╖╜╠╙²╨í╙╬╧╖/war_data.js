/** 合并所有学科题库 */
const allSubjectQuestions = [
    ...mathChoiceQuestions,
    ...mathCalcQuestions,
    ...englishChoiceQuestions,
    ...pinyinChoiceQuestions
];

/**
 * 根据学科获取题库
 * @param {string} subject - 学科类型
 * @param {string} [type] - 题目类型（可选）
 * @returns {Array} 题目数组
 */
function getQuestionsBySubject(subject, type = null) {
    let questions = allSubjectQuestions.filter(q => q.subject === subject);
    if (type) {
        questions = questions.filter(q => q.type === type);
    }
    return questions;
}

/**
 * 根据ID获取题目
 * @param {string} id - 题目ID
 * @returns {Object|null} 题目对象
 */
function getQuestionById(id) {
    return allSubjectQuestions.find(q => q.id === id) || null;
}

/**
 * 获取当前城市的战斗题目（城市专属 + 通用混合）
 * @param {string} cityId - 城市ID
 * @returns {Array} 混合后的题目数组
 */
function getBattleQuestions(cityId) {
    const cityQs = cityBattleQuestions[cityId] || [];
    const mixed = shuffle([...cityQs, ...generalBattleQuestions]);
    if (typeof Game !== 'undefined' && Game.log) {
        Game.log(`战斗题目混合完成: ${cityQs.length}道城市题 + ${generalBattleQuestions.length}道通用题 = ${mixed.length}道`);
    }
    return mixed;
}


function build(city, dists) {
  var r = {};
  for (var dname in dists) {
    if (!dists.hasOwnProperty(dname)) continue;
    r[dname] = {};
    var streets = dists[dname];
    for (var sname in streets) {
      if (!streets.hasOwnProperty(sname)) continue;
      r[dname][sname] = gen(city, dname, sname, streets[sname]);
    }
  }
  return r;
}


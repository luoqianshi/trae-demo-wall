def seed_database(db):
    """如果数据库为空则写入种子数据。db 为 SQLAlchemy Session 实例。"""
    if db.query(City).count() > 0:
        return

    # 写入城市
    for name in CITIES:
        db.add(City(name=name))

    # 写入城市别称
    for city_name, aliases in CITY_ALIASES.items():
        for alias in aliases:
            db.add(CityAlias(city_name=city_name, alias=alias))

    # 写入天气
    for city, w in WEATHER_DATA.items():
        db.add(Weather(city=city, text=w['text'], temp=w['temp'], icon=w['icon']))

    # 写入活动库
    for act in ACTIVITIES:
        # city 字段：未指定的活动适用于所有城市
        city_list = act.get('city', CITIES)
        # groups 字段：未指定的活动适用于所有人群
        group_list = act.get('groups', ALL_GROUPS)
        # transport 字段：未指定的活动适用于所有交通方式
        transport_list = act.get('transport', ALL_TRANSPORT)
        db.add(Activity(
            id=act['id'],
            name=act['name'],
            type=act['type'],
            mood=act['mood'],
            energy=act['energy'],
            interests=act['interests'],
            city=city_list,
            duration=act['duration'],
            cost=act['cost'],
            slot=act['slot'],
            tip=act['tip'],
            location=act.get('location', ''),
            address=act.get('address', ''),
            groups=group_list,
            transport=transport_list,
            intensity=act.get('intensity', 2),
        ))

    db.commit()
    print('[seed] 数据库种子数据已写入：{} 个城市, {} 条活动'.format(
        len(CITIES), len(ACTIVITIES)))

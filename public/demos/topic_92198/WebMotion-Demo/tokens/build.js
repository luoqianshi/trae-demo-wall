/**
 * tokens/build.js — 从 source.json 生成 tokens.css + tokens.js
 * 用法: node tokens/build.js
 * 作为 WebMotion 构建流程的一部分，确保 CSS/JS 始终与 source.json 同步
 */

const fs = require('fs');
const path = require('path');

const source = JSON.parse(fs.readFileSync(path.join(__dirname, 'source.json'), 'utf8'));

// ── 递归扁平化：将嵌套对象转为 CSS 变量名 ──
function flatten(obj, prefix = '') {
  const result = {};
  for (const [key, val] of Object.entries(obj)) {
    if (val && typeof val.value !== 'undefined') {
      result[prefix + key] = { value: val.value, type: val.type };
    } else if (typeof val === 'object' && !Array.isArray(val)) {
      Object.assign(result, flatten(val, prefix + key + '-'));
    }
  }
  return result;
}

// ── 递归扁平化为 JS 对象路径 ──
function flattenJS(obj, prefix = '') {
  const result = {};
  for (const [key, val] of Object.entries(obj)) {
    if (val && typeof val.value !== 'undefined') {
      result[prefix + key] = val.value;
    } else if (typeof val === 'object' && !Array.isArray(val)) {
      Object.assign(result, flattenJS(val, prefix + key + '.'));
    }
  }
  return result;
}

// ── 构建嵌套对象 ──
function buildNested(flat) {
  const result = {};
  for (const [key, val] of Object.entries(flat)) {
    const parts = key.split('.');
    let current = result;
    for (let i = 0; i < parts.length - 1; i++) {
      if (!current[parts[i]]) current[parts[i]] = {};
      current = current[parts[i]];
    }
    current[parts[parts.length - 1]] = val;
  }
  return result;
}

const flatTokens = flatten(source);
const flatJS = flattenJS(source);
const nested = buildNested(flatJS);

// ── 生成 CSS ──
let css = `/* ═══════════════════════════════════════════════════════════\n`;
css += `   WebMotion Design Tokens — AUTO-GENERATED from source.json\n`;
css += `   DO NOT EDIT THIS FILE DIRECTLY\n`;
css += `   Run: node tokens/build.js\n`;
css += `   ═══════════════════════════════════════════════════════════ */\n\n`;
css += `:root {\n`;

for (const [name, { value, type }] of Object.entries(flatTokens)) {
  const unit = type === 'dimension' ? 'px' : '';
  css += `  --${name}: ${value}${unit};\n`;
}

css += `}\n`;

fs.writeFileSync(path.join(__dirname, 'tokens.css'), css, 'utf8');
console.log('✓ tokens.css generated');

// ── 生成 JS ──
let js = `// ═══════════════════════════════════════════════════════════\n`;
js += `// WebMotion Design Tokens — AUTO-GENERATED from source.json\n`;
js += `// DO NOT EDIT THIS FILE DIRECTLY\n`;
js += `// Run: node tokens/build.js\n`;
js += `// ═══════════════════════════════════════════════════════════\n\n`;

js += `const TOKENS = `;
js += JSON.stringify(nested, null, 2)
  .replace(/"([^"]+)":/g, '$1:')
  .replace(/: "([^"]*px)"/g, ': "$1"')
  .replace(/: "([^"]*s)"/g, ': "$1"');

js += `;\n\n`;
js += `// 兼容全局访问（非 ESM 环境）\n`;
js += `if (typeof window !== 'undefined') window.TOKENS = TOKENS;\n`;
js += `if (typeof module !== 'undefined') module.exports = TOKENS;\n`;

fs.writeFileSync(path.join(__dirname, 'tokens.js'), js, 'utf8');
console.log('✓ tokens.js generated');
console.log('✓ Build complete');
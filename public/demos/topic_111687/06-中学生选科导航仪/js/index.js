/* 页面加载时初始化 */
window.onload = function(){
  var province = localStorage.getItem('province');
  var mode = localStorage.getItem('mode');

  /* 显示省份信息 */
  var infoEl = document.getElementById('provinceInfo');
  if(province && mode){
    infoEl.textContent = province + ' · ' + mode + '模式 · 6个问题找到最适合的选科组合';
  } else {
    infoEl.textContent = '请先选择省份';
    setTimeout(function(){
      if(confirm('未检测到省份信息，是否返回登录页选择省份？')){
        location.href = 'html/login.html';
      }
    }, 500);
    mode = '3+1+2';
  }

  /* 根据模式渲染选科组合 */
  renderCombos(mode);

  /* 加载能力画像 */
  loadAbilityScores();
};

/* 加载能力画像 */
function loadAbilityScores() {
  var scoresStr = localStorage.getItem('abilityScores');
  var profile = localStorage.getItem('abilityProfile');
  var completed = localStorage.getItem('quizCompleted');

  if (scoresStr && profile && completed) {
    var scores = JSON.parse(scoresStr);

    /* 更新数值 */
    document.getElementById('valLogic').textContent = scores.logic;
    document.getElementById('valMemory').textContent = scores.memory;
    document.getElementById('valHandsOn').textContent = scores.handsOn;
    document.getElementById('valExpression').textContent = scores.expression;
    document.getElementById('valSpatial').textContent = scores.spatial;

    /* 动画更新柱状图高度 */
    setTimeout(function() {
      document.getElementById('barLogic').style.height = scores.logic + '%';
      document.getElementById('barMemory').style.height = scores.memory + '%';
      document.getElementById('barHandsOn').style.height = scores.handsOn + '%';
      document.getElementById('barExpression').style.height = scores.expression + '%';
      document.getElementById('barSpatial').style.height = scores.spatial + '%';
    }, 100);

    /* 更新描述 */
    document.getElementById('radarDesc').textContent = profile;
    document.getElementById('resultTitle').textContent = '📊 你的能力画像';

    /* 按钮改为重新测评 */
    var btn = document.getElementById('radarBtn');
    btn.textContent = '🔄 重新测评';
    btn.href = 'html/quiz.html';
  } else {
    /* 未测评状态 — 显示引导 */
    document.getElementById('resultTitle').textContent = '📊 能力测评';
    document.getElementById('radarDesc').textContent = '完成6道测评题，生成你的专属五维能力画像，精准推荐最适合的选科组合';
  }
}


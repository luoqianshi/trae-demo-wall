/* 关闭专业详情弹窗 */
function closeMajorModal(event) {
  if (event && event.target && event.target.id !== 'majorModal' && event.target.className !== 'modal-close') {
    return;
  }
  document.getElementById('majorModal').classList.remove('show');
  document.body.style.overflow = '';
}
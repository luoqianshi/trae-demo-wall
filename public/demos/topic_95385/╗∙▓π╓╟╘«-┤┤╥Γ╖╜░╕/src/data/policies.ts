export function getHotPolicies() {
  return policies.slice(0, 3)
}

export function getPoliciesByCategory(categoryId: string) {
  return policies.filter(p => p.category === categoryId)
}

export function searchPolicies(keyword: string) {
  return policies.filter(p => 
    p.title.includes(keyword) || 
    p.summary.includes(keyword) ||
    p.tags.some(tag => tag.includes(keyword))
  )
}

export function getPolicyById(id: string) {
  return policies.find(p => p.id === id)
}
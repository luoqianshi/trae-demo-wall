export const getWordsByDifficulty = (difficulty: number): Word[] => {
  return words.filter(w => w.difficulty <= difficulty);
};

export const getRandomWord = (maxDifficulty: number): Word => {
  const availableWords = getWordsByDifficulty(maxDifficulty);
  const randomIndex = Math.floor(Math.random() * availableWords.length);
  return availableWords[randomIndex];
};

export const getWordById = (id: string): Word | undefined => {
  return words.find(w => w.id === id);
};

export const getWordsByPartOfSpeech = (partOfSpeech: Word['partOfSpeech']): Word[] => {
  return words.filter(w => w.partOfSpeech === partOfSpeech);
};

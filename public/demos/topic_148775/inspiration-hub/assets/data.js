/* 工具：根据 id 取案例，先查用户发布的接力对话，再查内置 CASES，找不到则回退到第一个 */
window.getCase = function (id) {
  // 优先查 localStorage 中的用户接力对话
  if (id && id.indexOf('remix-') === 0) {
    try {
      var list = JSON.parse(localStorage.getItem('inspirohub_remixes') || '[]');
      for (var i = 0; i < list.length; i++) {
        if (list[i].id === id) return list[i];
      }
    } catch (e) {}
  }
  return window.CASES[id] || Object.values(window.CASES)[0];
};

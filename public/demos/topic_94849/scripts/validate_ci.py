def get_pingze(char: str) -> str:
    if not char or not char.strip():
        return ""
    
    if char in PINGZE_EXCEPTIONS:
        return PINGZE_EXCEPTIONS[char]
    
    if is_rusheng(char):
        return "仄"
    
    try:
        result = pinyin(char, style=Style.TONE3)
        if result and result[0]:
            pinyin_str = result[0][0]
            if pinyin_str[-1] in '12':
                return "平"
            elif pinyin_str[-1] in '34':
                return "仄"
    except Exception:
        pass
    
    return "中"

def parse_text(text: str) -> List[str]:
    lines = re.split(r'[，。！？；：\n\r]', text)
    lines = [line.strip() for line in lines if line.strip()]
    return lines

def validate_word_count(lines: List[str], pattern: str, verbose: bool) -> bool:
    pattern_lines = [p.strip() for p in pattern.split("，")]
    valid = True
    
    if len(lines) != len(pattern_lines):
        if verbose:
            print(f"✗ 句子数量不符：期望 {len(pattern_lines)} 句，实际 {len(lines)} 句")
        return False
    
    for i, (line, pat) in enumerate(zip(lines, pattern_lines)):
        expected_len = len(pat)
        actual_len = len(line)
        if actual_len != expected_len:
            if verbose:
                print(f"✗ 第 {i+1} 句字数不符：期望 {expected_len} 字，实际 {actual_len} 字（'{line}'）")
            valid = False
    
    if verbose and valid:
        print("✓ 字数校验通过")
    
    return valid

def validate_pingze(lines: List[str], pattern: str, verbose: bool) -> bool:
    pattern_lines = [p.strip() for p in pattern.split("，")]
    valid = True
    
    for i, (line, pat) in enumerate(zip(lines, pattern_lines)):
        for j, (char, expected) in enumerate(zip(line, pat)):
            actual = get_pingze(char)
            if expected == "中":
                continue
            if actual != expected:
                if verbose:
                    print(f"✗ 第 {i+1} 句第 {j+1} 字平仄不符：期望 '{expected}'，实际 '{actual}'（'{char}'）")
                valid = False
    
    if verbose and valid:
        print("✓ 平仄校验通过")
    
    return valid

def get_char_yunbu(char: str) -> Optional[str]:
    for yunbu, chars in YUNBU_DATA.items():
        if char in chars:
            return yunbu
    
    try:
        result = pinyin(char, style=Style.TONE3)
        if result and result[0]:
            pinyin_str = result[0][0]
            rhyme_part = pinyin_str[:-1] if pinyin_str[-1].isdigit() else pinyin_str
            
            for yunbu, chars in YUNBU_DATA.items():
                for c in chars:
                    c_pinyin = pinyin(c, style=Style.TONE3)[0][0]
                    c_rhyme = c_pinyin[:-1] if c_pinyin[-1].isdigit() else c_pinyin
                    if rhyme_part == c_rhyme:
                        return yunbu
    except Exception:
        pass
    
    return None

def validate_rhyme(lines: List[str], rhymes: str, verbose: bool) -> bool:
    rhyme_flags = [int(r) for r in rhymes.split(",")]
    rhyme_lines = [(i, line) for i, (line, flag) in enumerate(zip(lines, rhyme_flags)) if flag == 1]
    
    if len(rhyme_lines) < 2:
        if verbose:
            print(f"✓ 韵脚校验通过（仅 {len(rhyme_lines)} 个韵脚）")
        return True
    
    first_yunbu = get_char_yunbu(rhyme_lines[0][1][-1])
    valid = True
    
    if verbose:
        print(f"  韵脚分析：")
    
    for i, (line_idx, line) in enumerate(rhyme_lines):
        char = line[-1]
        yunbu = get_char_yunbu(char)
        
        if verbose:
            print(f"    第 {line_idx+1} 句韵脚 '{char}' → 韵部 '{yunbu}'")
        
        if i > 0 and yunbu != first_yunbu:
            if verbose:
                print(f"✗ 第 {line_idx+1} 句韵脚 '{char}'（韵部 '{yunbu}'）与首韵脚（韵部 '{first_yunbu}'）不押韵")
            valid = False
    
    if verbose and valid:
        print("✓ 韵脚校验通过")
    
    return valid

def validate_ci(cipai: str, text: str, verbose: bool = False) -> Dict[str, bool]:
    if cipai not in CIPAI_DATA:
        print(f"错误：词牌 '{cipai}' 未找到")
        print(f"支持的词牌：{', '.join(CIPAI_DATA.keys())}")
        return {"valid": False}
    
    data = CIPAI_DATA[cipai]
    lines = parse_text(text)
    
    if verbose:
        print(f"\n=== 校验词牌：{cipai} ===")
        print(f"原文：{text}")
        print(f"分句：{lines}")
        print()
    
    results = {}
    
    results["word_count"] = validate_word_count(lines, data["pattern"], verbose)
    results["pingze"] = validate_pingze(lines, data["pattern"], verbose)
    results["rhyme"] = validate_rhyme(lines, data["rhymes"], verbose)
    
    results["valid"] = all([results["word_count"], results["pingze"], results["rhyme"]])
    
    if verbose:
        print()
        if results["valid"]:
            print("🎉 校验通过！")
        else:
            print("❌ 校验未通过")
    
    return results

def main():
    parser = argparse.ArgumentParser(description="宋词格律校验工具")
    parser.add_argument("--cipai", required=True, help="词牌名")
    parser.add_argument("--text", required=True, help="宋词文本")
    parser.add_argument("--verbose", action="store_true", help="显示详细信息")
    
    args = parser.parse_args()
    
    validate_ci(args.cipai, args.text, args.verbose)

if __name__ == "__main__":
    main()

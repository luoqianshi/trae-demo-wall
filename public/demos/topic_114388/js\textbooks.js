/**
 * 搜索教材
 */
export function searchTextbooks(keyword) {
    if (!keyword) return [];
    const kw = keyword.toLowerCase();
    const results = [];
    for (const cat of textbookCategories) {
        for (const tb of cat.textbooks) {
            const searchable = `${tb.name} ${tb.publisher} ${tb.points.join(' ')}`.toLowerCase();
            if (searchable.includes(kw)) {
                results.push({ ...tb, categoryName: cat.name, categoryIcon: cat.icon, categoryId: cat.id });
            }
        }
    }
    return results;
}

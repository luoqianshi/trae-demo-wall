/**
 * 按科目名推荐重点
 * @param {string} name 科目名称
 * @param {number} difficulty 难度 1/2/3
 * @returns {Array<{point:string, source:string, confidence:number}>}
 */
export function recommendByName(name, difficulty = 2) {
    if (!name) return [];
    const trimmed = String(name).trim();
    // 1. 完整命中
    let base = KNOWLEDGE_BASE[trimmed];
    let source = '完全匹配';
    let confidence = 0.95;
    // 2. 别名匹配
    if (!base) {
        const alias = ALIASES[trimmed.toLowerCase()];
        if (alias && KNOWLEDGE_BASE[alias]) {
            base = KNOWLEDGE_BASE[alias];
            source = `别名匹配（${alias}）`;
            confidence = 0.85;
        }
    }
    // 3. 模糊包含匹配
    if (!base) {
        for (const key of Object.keys(KNOWLEDGE_BASE)) {
            if (trimmed.includes(key) || key.includes(trimmed)) {
                base = KNOWLEDGE_BASE[key];
                source = `模糊匹配（${key}）`;
                confidence = 0.7;
                break;
            }
        }
    }
    if (!base) {
        return []; // 完全没匹配上
    }
    const filtered = adjustByDifficulty(base, difficulty);
    return filtered.map(p => ({ point: p, source, confidence }));
}

/**
 * 检查知识库是否收录该科目
 */
export function hasSubject(name) {
    if (!name) return false;
    const trimmed = String(name).trim();
    if (KNOWLEDGE_BASE[trimmed]) return true;
    if (ALIASES[trimmed.toLowerCase()] && KNOWLEDGE_BASE[ALIASES[trimmed.toLowerCase()]]) return true;
    for (const key of Object.keys(KNOWLEDGE_BASE)) {
        if (trimmed.includes(key) || key.includes(trimmed)) return true;
    }
    return false;
}

/**
 * 获取所有已收录的科目列表（用于提示）
 */
export function getAllSubjects() {
    return Object.keys(KNOWLEDGE_BASE).sort((a, b) => a.localeCompare(b, 'zh-CN'));
}

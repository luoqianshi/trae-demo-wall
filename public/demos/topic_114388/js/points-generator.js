/* ================ 难度调整 ================ */
// 难度 1 简单：取前 60%；难度 2 中等：取前 80%；难度 3 困难：取 100%
function adjustByDifficulty(points, difficulty) {
    if (!points.length) return [];
    const ratio = { 1: 0.6, 2: 0.8, 3: 1.0 }[difficulty] || 0.8;
    return points.slice(0, Math.max(3, Math.round(points.length * ratio)));
}


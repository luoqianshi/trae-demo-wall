/**
 * 为单条释义结果匹配建议模板
 * 评分逻辑：关键词匹配权重2，主题匹配权重1，取分数最高的前2个模板
 */
export function matchAdviceTemplates(
  wisdom: string,
  translation: string,
  themes: string[],
): AdviceTemplate[] {
  const text = wisdom + translation;
  const scored: { template: AdviceTemplate; score: number }[] = [];

  for (const template of ADVICE_TEMPLATES) {
    let score = 0;

    // 关键词匹配（权重2）
    for (const kw of template.matchKeywords) {
      if (text.includes(kw)) score += 2;
    }

    // 主题匹配（权重1）
    for (const theme of template.matchThemes) {
      if (themes.includes(theme)) score += 1;
    }

    if (score > 0) {
      scored.push({ template, score });
    }
  }

  // 按分数排序，取前2个
  scored.sort((a, b) => b.score - a.score);
  const matched = scored.slice(0, 2).map((s) => s.template);

  // 兜底：若无匹配，使用通用建议
  if (matched.length === 0) {
    matched.push(FALLBACK_ADVICE);
  }

  return matched;
}
